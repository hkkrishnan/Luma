const CACHE = "northstar-lite-shell-v14";
const SHELL = [
  "./", "./index.html", "./app.js", "./northstar-markdown.js",
  "./lite-enhancements.css", "./manifest.webmanifest",
  "./icons/northstar-192.svg", "./icons/northstar-512.svg",
];

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(SHELL)).then(() => self.skipWaiting()));
});
self.addEventListener("activate", (event) => {
  event.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key)))).then(() => self.clients.claim()));
});
self.addEventListener("fetch", (event) => {
  if (event.request.method !== "GET") return;
  const url = new URL(event.request.url);
  if (url.origin !== self.location.origin) return;
  const relative = url.pathname.endsWith("/") ? "./" : `./${url.pathname.split("/").pop()}`;
  if (!SHELL.includes(relative) && event.request.mode !== "navigate") return;
  if (event.request.mode === "navigate") {
    event.respondWith(fetch(event.request).catch(() => caches.match("./index.html")));
    return;
  }
  event.respondWith(caches.match(event.request).then((cached) => cached || fetch(event.request).then((response) => {
    if (response.ok) caches.open(CACHE).then((cache) => cache.put(event.request, response.clone()));
    return response;
  })));
});
